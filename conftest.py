r"""Куда уходят временные файлы тестов.

Зачем этот файл
---------------
В корне проекта накопились десятки папок `zagent-bench-*` и `tmp*`.
Виновник найден: `tempfile.gettempdir()` возвращал не системную папку,
а **корень проекта**, поэтому каждый `mkdtemp()` создавал папку прямо
здесь.

`TEMP` при этом указывает на `C:\Users\HP\AppData\Local\Temp`, и папка
существует. Значит, `tempfile` её отверг и перешёл к следующему
кандидату — текущему каталогу. Почему отверг — отдельная загадка
внутри стандартной библиотеки, но обойти её просто: задать временную
папку явно, до того как что-либо успеет создаться.

Что делается
------------
`tempfile.tempdir` выставляется до сбора тестов, при импорте файла.
Это влияет и на прямые вызовы `tempfile`, и на `pytest`, который
создаёт свои каталоги через тот же модуль.

Почему важно, что это `conftest.py`
----------------------------------
Pytest импортирует корневой `conftest.py` до сбора тестов, раньше
любого теста. Поэтому переменная выставлена гарантированно, а не
«если кто-то первым делом вспомнил».

Побочная польза: папка `tmp` в `.gitignore` (если она там есть),
иначе временные файлы попадут в репозиторий.
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path

#: Корень проекта: папка на уровень выше `tests` и `conftest.py`.
ROOT = Path(__file__).resolve().parent

#: Куда складывать всё временное. Отдельная папка, а не корень:
#: в корне её содержимое было бы не отличить от настоящих файлов
#: проекта — именно так и появились сотни папок.
TMP_DIR = ROOT / "tmp"


def point_tempfile_at_project_tmp() -> Path:
    """Направить `tempfile` в папку `tmp` внутри проекта.

    Папка создаётся заранее: первый же `mkdtemp()` мог бы её не
    найти и откатиться обратно в корень.
    """
    try:
        TMP_DIR.mkdir(parents=True, exist_ok=True)
        tempfile.tempdir = str(TMP_DIR)
        # Некоторые сторонние библиотеки читают переменные окружения,
        # а не `tempfile.tempdir`. Им тоже нужен правильный путь.
        os.environ["TMPDIR"] = str(TMP_DIR)
        os.environ["TEMP"] = str(TMP_DIR)
        os.environ["TMP"] = str(TMP_DIR)
    except OSError:
        # Не смогли — продолжаем как было. Тесты, которым нужна
        # временная папка, получат системную и отработают, а те, что
        # создают мусор в корне, вернутся к прежнему поведению.
        # Это лучше, чем уронить весь прогон из-за правки пути.
        pass
    return TMP_DIR


#: Выставляется при импорте, а не фикстурой: фикстура запускается
#: уже после того, как pytest успел создать свои каталоги.
point_tempfile_at_project_tmp()