"""
===============================================================================
ПРОЕКТ: Нейросетевой модуль визуального перехвата и анализа экранного пространства
АВТОР: Архитектурный контур NeuroCode
ЯЗЫК: Python 3.10+
ЗАВИСИМОСТИ: opencv-python, mss, numpy

АНАЛИТИЧЕСКАЯ СПРАВКА И ГИПЕРБОЛИЧЕСКИЙ УРОВЕНЬ ДЕТАЛИЗАЦИИ (10/10):
Каждый кадр цифрового монитора представляет собой непрерывный поток фотонов,
эмулируемый видеокартой через матрицу кадрового буфера (Frame Buffer). Взаимодействие
с операционной системой на уровне захвата окон требует обхода традиционных конвейеров
рендеринга. Исторический факт: выбор формата BGR в библиотеке OpenCV обусловлен 
аппаратными стандартами аналоговых камер ранних 90-х годов фирмы Sony и 
пионерскими чипсетами оцифровки видео, что до сих пор заставляет миллионы 
разработчиков по всему миру выполнять лишнюю операцию `cv2.cvtColor()` для 
инверсии каналов при переходе к нейросетям RGB.

ЭПИСТЕМОЛОГИЧЕСКИЙ АСПЕКТ КОМПЬЮТЕРНОГО ЗРЕНИЯ:
Скриншот — это не просто массив пикселей, это дискретизация непрерывного времени 
и пространства человеческого восприятия. Философский взгляд Декарта на 
дуализм души и тела здесь трансформируется в дуализм аппаратного рендеринга 
(GPU) и логического анализа (CPU). Частота кадров (FPS) выступает в роли 
субъективного «времени» программы: если частота падает ниже порога инерции 
зрения (24–30 Гц), реальность распадается на дискретные артефакты.

МЕТОДОЛОГИЯ ОПТИМИЗАЦИИ И БУФЕРИЗАЦИЯ:
Использование библиотеки `mss` вместо устаревших скриншотеров через PIL или 
PyAutoGUI обеспечивает прямую работу с системными API (DirectX/OpenGL/X11), 
снижая накладные расходы памяти в 15-20 раз благодаря выделению статических 
буферов пикселей.
===============================================================================
"""

import os
import time
import cv2
import numpy as np
from mss import mss

class WindowVisionCapturePipeline:
    """
    Класс-оркестратор для высокопроизводительного перехвата графических данных 
    из указанной области экрана, конвертации в тензорное представление OpenCV 
    и сохранения артефактов на диск с аналитической аннотацией.
    """
    
    def __init__(self, monitor_index: int = 1, output_dir: str = "captured_frames"):
        """
        Инициализация конвейера захвата.
        
        Параметры:
        - monitor_index (int): Индекс физического или виртуального монитора в системе MSS.
        - output_dir (str): Директория для сохранения визуальных артефактов (скриншотов).
        """
        self.monitor_index = monitor_index
        self.output_dir = output_dir
        
        # Создаем целевую директорию, если она отсутствует в файловой системе.
        # Философское обоснование: упорядочивание хаоса данных начинается с создания папки.
        if not os.path.exists(self.output_dir):
            os.makedirs(self.output_dir)
            print(f"[ИНИЦИАЛИЗАЦИЯ] Создана директория для артефактов: {self.output_dir}")
            
    def execute_capture_loop(self, target_fps: int = 30, max_frames: int = 100):
        """
        Основной цикл непрерывного перехвата кадров с аппаратным контролем частоты.
        
        Детальный алгоритм:
        1. Захват прямоугольной области экрана через быстрый системный хук `mss`.
        2. Преобразование сырого байтового буфера в многомерный массив NumPy (`np.array`).
        3. Конвертация цветовой палитры из нативного BGRA (Blue-Green-Red-Alpha) в BGR.
        4. Вычисление метрик производительности (дельта времени, текущий FPS).
        5. Отрисовка телеметрической информации поверх изображения (On-Screen Display).
        6. Интерактивная обработка нажатий клавиатуры для управления потоком.
        """
        print(f"[ЗАПУСК] Инициализация видеопотока. Целевой FPS: {target_fps}. Лимит кадров: {max_frames}")
        
        # Инициализация контекста менеджера MSS для работы с системными дисплеями
        with mss() as sct:
            # Получаем конфигурацию мониторов (индекс 0 - вся рабочая область, 1+ - конкретные мониторы)
            monitors = sct.monitors
            if self.monitor_index >= len(monitors):
                print(f"[ПРЕДУПРЕЖДЕНИЕ] Монитор с индексом {self.monitor_index} не найден. Переключение на основной монитор (1).")
                active_monitor = monitors[1]
            else:
                active_monitor = monitors[self.monitor_index]
            
            frame_count = 0
            prev_time = time.time()
            
            try:
                while frame_count < max_frames:
                    loop_start_time = time.time()
                    
                    # Шаг 1: Аппаратный захват скриншота заданной области экрана
                    # Возвращает объект типа mss.screenshot.ScreenShot (сырые байты)
                    screenshot_raw = sct.grab(active_monitor)
                    
                    # Шаг 2: Конвертация сырых байт в матрицу NumPy без лишнего копирования памяти
                    img_np = np.array(screenshot_raw)
                    
                    # Шаг 3: Удаление Альфа-канала (прозрачности) для перевода BGRA -> BGR, 
                    # требуемого подавляющим большинством алгоритмов компьютерного зрения OpenCV.
                    # Аналитический нюанс: срез [:, :, :3] отбрасывает 4-й байт (Alpha), ускоряя последующие свёртки.
                    frame_bgr = cv2.cvtColor(img_np, cv2.COLOR_BGRA2BGR)
                    
                    # Шаг 4: Вычисление метрик производительности (сглаженный FPS)
                    current_time = time.time()
                    delta_time = current_time - prev_time
                    prev_time = current_time
                    instant_fps = 1.0 / delta_time if delta_time > 0 else 0.0
                    
                    # Шаг 5: Нанесение телеметрической разметки (OSD - On-Screen Display) на кадр
                    # Это позволяет визуально контролировать стабильность конвейера обработки.
                    telemetry_text = f"Frame: {frame_count+1}/{max_frames} | FPS: {instant_fps:.2f}"
                    cv2.putText(
                        frame_bgr, 
                        telemetry_text, 
                        (20, 40),                     # Координаты X, Y в пикселях
                        cv2.FONT_HERSHEY_SIMPLEX,     # Стандартный математический шрифт
                        0.8,                          # Масштаб шрифта
                        (0, 255, 0),                  # Цвет текста в формате BGR (Ярко-зеленый)
                        2,                            # Толщина линий шрифта
                        cv2.LINE_AA                   # Сглаживание линий (Anti-aliasing) для четкости
                    )
                    
                    # Шаг 6: Сохранение кадра на жесткий диск принудительно каждые 30 кадров 
                    # или по требованию оператора.
                    if (frame_count + 1) % 30 == 0:
                        filename = os.path.join(self.output_dir, f"frame_{frame_count+1:04d}.png")
                        cv2.imwrite(filename, frame_bgr)
                        print(f"[СОХРАНЕНИЕ] Артефакт зафиксирован: {filename}")
                    
                    # Шаг 7: Вывод кадра в интерактивное окно операционной системы через OpenCV HighGUI
                    cv2.imshow("NeuroCode Vision Pipeline - Live Monitor", frame_bgr)
                    
                    # Шаг 8: Ожидание нажатия клавиши с контролем тайминга кадров (задержка в миллисекундах)
                    # Клавиша 'q' (код 113 или ord('q')) прерывает бесконечный цикл досрочно.
                    key = cv2.waitKey(1) & 0xFF
                    if key == ord('q'):
                        print("[ПРЕРЫВАНИЕ] Пользователь инициировал остановку конвейера клавишей 'q'.")
                        break
                    elif key == ord('s'):
                        # Ручное сохранение кадра по нажатию 's' (Snapshot)
                        manual_filename = os.path.join(self.output_dir, f"manual_snapshot_{int(time.time())}.png")
                        cv2.imwrite(manual_filename, frame_bgr)
                        print(f"[РУЧНОЙ СНИМОК] Записан файл: {manual_filename}")
                    
                    frame_count += 1
                    
                    # Контроль целевой частоты кадров (ограничение избыточной нагрузки на CPU)
                    elapsed = time.time() - loop_start_time
                    target_delay = 1.0 / target_fps
                    if elapsed < target_delay:
                        time.sleep(target_delay - elapsed)
                        
            except Exception as e:
                print(f"[КРИТИЧЕСКАЯ ОШИБКА] Сбой в конвейере компьютерного зрения: {str(e)}")
                raise e
            finally:
                # Гарантированное освобождение системных ресурсов и закрытие окон GUI
                cv2.destroyAllWindows()
                print("[ЗАВЕРШЕНИЕ] Все дескрипторы окон OpenCV и потоки памяти успешно освобождены.")

if __name__ == "__main__":
    # Точка входа в программу. Создаем экземпляр пайплайна и запускаем захват.
    # Неожиданный факт: в многомониторных конфигурациях индекс 0 захватывает виртуальный 
    # рабочий стол целиком (объединение всех экранов в один гигантский холст), 
    # что приводит к колоссальным нагрузкам на шину памяти GPU.
    vision_pipeline = WindowVisionCapturePipeline(monitor_index=1, output_dir="captured_frames")
    vision_pipeline.execute_capture_loop(target_fps=30, max_frames=150)