/* Призма — переключение светлых тонов.

   Скрипт маленький намеренно. У заглушки нет задачи быть приложением:
   здесь нужен ровно один интерактив, который честно показывает, что
   страница живая, и который позволяет глазами проверить читаемость
   текста на разных светлых фонах — цифры в редакторе эту проверку
   не заменяют.

   Наборы тонов живут в CSS (html[data-palette="N"]), здесь только
   переключение атрибута. Разделение сделано потому, что тогда стили
   остаются читаемыми как шкала, а скрипт не превращается в место,
   где живут цвета.

   Тон намеренно не запоминается в localStorage: заглушка не должна
   оставлять след в браузере посетителя и не должна удивлять человека
   другим фоном при следующем открытии.
*/
(function () {
  'use strict';

  // Названия тонов. Порядок совпадает с порядком в CSS — если добавить
  // набор там, его надо добавить и здесь, иначе кнопка станет врать.
  var TONES = ['дневной', 'холодный', 'бумажный', 'контрастный'];

  var root = document.documentElement;
  var btn = document.getElementById('tone-next');
  var label = document.getElementById('tone-name');

  // Страница должна работать и без этого скрипта: он только добавляет
  // кнопку. Если чего-то нет — молча выходим, страница остаётся читаемой.
  if (!btn || !label) { return; }

  function current() {
    var n = parseInt(root.getAttribute('data-palette'), 10);
    return isNaN(n) ? 0 : n;
  }

  function apply(index) {
    root.setAttribute('data-palette', String(index));
    label.textContent = TONES[index];
  }

  // Круговой перебор: после последнего тона возвращаемся к первому.
  // Один клик — один тон, без «вперёд/назад», потому что разница между
  // соседними тонами тонкая и два направления только путают.
  btn.addEventListener('click', function () {
    apply((current() + 1) % TONES.length);
  });

  // Начальное значение подставляем один раз на старте, чтобы подпись
  // совпадала с реально применённым тоном даже если атрибут меняли руками.
  apply(current());
})();