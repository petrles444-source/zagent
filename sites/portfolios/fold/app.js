'use strict';
/* app.js — «Складка». Одно действие на всю страницу: угол сгиба.
 *
 * Почему именно оно и почему оно единственное. У страницы про
 * читаемость на почти белом снимке, и проверить это можно только
 * двигая лист: пока он лежит ровно, приём «текст на бумаге, а не на
 * снимке» ничем не подтверждён. Всё остальное — стили и разметка.
 *
 * Почему так мало кода. Угол сгиба — это одно число, которое
 * одновременно живёт в трёх местах: в CSS-переменной --fold на листе
 * (ею считается rotateX и прозрачность тени сгиба), в ползунке
 * (чтобы не врать о положении после нажатия кнопки) и в подписи
 * (чтобы человек видел число, а не догадывался о нём по картинке).
 * Три источника правды в одном месте страницы — ровно столько, сколько
 * нужно, чтобы они не разошлись.
 *
 * Библиотек нет, внешних загрузок нет, шрифтов нет. Файл лежит рядом
 * и подключён с defer — к моменту запуска разметка уже собрана.
 */

/* Максимальный угол, который вообще имеет смысл показывать.
 * Взят из max в разметке, а не зашит в CSS, потому что одно число
 * не должно жить в двух файлах: если поменять предел в разметке,
 * кнопка «сложить» подстроится сама. */
var MAX_FOLD = 48;

/* Угол, в который кнопка складывает лист. Не максимум: на 48
 * градусах нижние полосы сжимаются до нечитаемой полоски, и
 * демонстрация выглядит как поломка, а не как складка. 40 —
 * это тот предел, где складка ещё видна как складка. */
var FOLDED = 40;

(function main() {
  var sheet = document.getElementById('sheet');
  var range = document.getElementById('fold');
  var out = document.getElementById('fold-out');
  var flip = document.getElementById('fold-flip');

  /* Если разметку поменяли, а скрипт забыли — страница обязана
   * остаться читаемой и просто не получить интерактива. Молчаливый
   * выход честнее исключения: заглушка не должна ломать каталог. */
  if (!sheet || !range || !out || !flip) {
    return;
  }

  /* Единственная функция записи состояния. Всё остальное только
   * вызывает её: тогда ползунок, кнопка и подпись не могут
   * разойтись между собой. */
  function setFold(deg) {
    /* Ограничиваем сверху и сниз: значение приходит из ползунка,
     * но setFold вызывается ещё и из кнопки, и защита от значения
     * вне диапазона дешевле, чем рассуждения о том, откуда оно. */
    var d = Math.max(0, Math.min(MAX_FOLD, Math.round(deg) || 0));

    /* --fold — число без единиц. Из него CSS считает и rotateX
     * (умножая на -1deg), и прозрачность тени сгиба (деля на 48).
     * Именно поэтому здесь строка, а не число: пользовательские
     * свойства без @property живут только строками. */
    sheet.style.setProperty('--fold', String(d));
    range.value = String(d);
    /* Градус в подписи — не украшение: без числа человек не может
     * сказать «у меня на 30 градусах текст ещё виден», а это ровно
     * тот вопрос, ради которого страница делалась. */
    out.textContent = d + '°';

    /* Название кнопки всегда говорит, что будет дальше, а не что
     * было раньше. Написать «сложить» на разложенном листе —
     * значит соврать. */
    flip.textContent = d > 0 ? 'развернуть' : 'сложить';
  }

  /* Ползунок — основной способ. input, а не change: лист должен
   * ехать за пальцем, иначе взаимодействие ощущается как «перетащил
   * и отпустил», а на телефоне это ещё и лишний шаг. */
  range.addEventListener('input', function () {
    setFold(Number(range.value));
  });

  /* Кнопка — тот же угол, двумя готовыми положениями. Именно два, а
   * не «перебрать»: список углов здесь ничего не объясняет человеку,
   * который хочет просто посмотреть, как загнётся лист. */
  flip.addEventListener('click', function () {
    var current = Number(range.value);
    setFold(current > 0 ? 0 : FOLDED);
  });

  /* Начальное значение берём из ползунка, а не задаём константой:
   * если в разметке max или value поменяют, стартовое положение
   * останется осмысленным само по себе. */
  setFold(Number(range.value) || 0);
})();