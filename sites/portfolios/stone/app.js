/* Камень — заглушка. Поведение страницы.

   Интерактив ровно один: лупа по фактуре. Ползунок (или сам снимок
   под мышью) двигает круглую линзу вверх-вниз по вертикальному
   снимку, линза показывает участок втрое крупнее, а рядом печатается
   точный тон пикселя под её центром и контраст текста на нём.

   Почему именно это, а не «красивый» эффект. Снимок очень тёмный:
   средний тон единица из 255, девяносто девятый процентиль около
   тридцати. На сто процентов браузера такая текстура выглядит как
   чёрный прямоугольник, и сказать по ней «вот фактура» нельзя —
   видно нечего. Лупа решает ровно эту задачу и честно: показывает
   то, что на снимке действительно есть, и ничего не придумывает.

   Почему показывается тон пикселя, а не только картинка. Увеличение
   субъективно: трижды увеличенная серая полоса выглядит «интереснее»
   без всяких на то оснований. Тон пикселя — число, его нельзя
   подрисовать, и по нему сразу видно, где снимок кончается и где
   начинаются царапины. Поэтому рядом с линзой стоит измерение.

   Почему линза на CSS, а не перерисовка в canvas. Линза — это вторая
   копия того же снимка, увеличенная трансформацией. Перерисовка
   исходника в canvas на каждый шаг ползунка заметно дороже и рвётся
   на слабом телефоне, а трансформацию браузер делает на видеокарте
   без единой перерисовки растра. Пиксели читаются только один раз —
   для тонов, и это отдельный кусок кода ниже.

   Ничего не выдумывается: числа на экране — измеренные. Если пиксели
   достать не удалось, скрипт честно пишет об этом, а не показывает
   заведомо придуманную величину, и лупа продолжает работать: она
   основана на CSS и от пикселей не зависит.

   Внешних загрузок нет, шрифты системные. Подключение с defer:
   разметка успевает собраться раньше, чем скрипт начнёт искать
   элементы. Второй экземпляр pic.jpg — это тот же адрес, браузер
   берёт его из кэша, дополнительного запроса не будет.
*/

(function () {
  'use strict';

  /* Во сколько раз линза увеличивает. Три — потому что четыре
     превращают царапину в расплывающееся пятно: при увеличении
     вчетверо JPEG-артефакты становятся больше самих царапин, и
     линза начинает врать. */
  var ZOOM = 3;

  /* Радиус линзы в долях от ширины колонки. Доля, а не пиксели,
     потому что колонка узкая на телефоне и широкая на мониторе:
     фиксированный радиус либо съедал бы половину снимка на
     телефоне, либо был неразличим на мониторе. */
  var RADIUS_RATIO = 0.17;

  /* Порог контраста WCAG AA для обычного текста. По нему считается,
     проходит ли подпись на том, что оказалось под линзой. */
  var MIN_CONTRAST = 4.5;

  /* Цвет подписи под снимком: метка «подпись под снимком» из CSS,
     что светлее остального её текста. На тёмном камне светлую
     подпись читать нечем, цвет другой не поставить.

     Значение скопировано из style.css, а не берётся из вычисленных
     стилей намеренно: getComputedStyle вернул бы строку с кучей
     пробелов и запятых, которую пришлось бы парсить вручную.
     Дублирование в одном файле хуже, чем парсинг CSS в рантайме,
     и оно заметно при правке тона — оба числа стоят рядом. */
  var BAND_DIM = [201, 192, 180];

  var frame = document.getElementById('frame');
  var loupe = document.getElementById('loupe');
  var loupePic = loupe ? loupe.querySelector('.loupe-pic') : null;
  var range = document.getElementById('loupe-y');
  var out = document.getElementById('probe-out');
  var pic = document.querySelector('.pic');

  if (!frame || !loupe || !loupePic || !range || !out || !pic) {
    return;
  }

  var canvas = null;
  var ctx = null;
  var pixels = null;
  var measured = false;

  /* ---- перевод цветов в относительную светлоту ----
     Формула из WCAG 2.x. Именно она, а не «на глаз по яркости»:
     контраст по этой формуле совпадает с тем, что считают
     проверяющие инструменты, поэтому число на странице можно
     сверять с их числом. */
  function channel(v) {
    var c = v / 255;
    return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
  }

  function luminance(rgb) {
    return 0.2126 * channel(rgb[0]) +
           0.7152 * channel(rgb[1]) +
           0.0722 * channel(rgb[2]);
  }

  function contrast(a, b) {
    var la = luminance(a);
    var lb = luminance(b);
    if (la < lb) {
      var t = la;
      la = lb;
      lb = t;
    }
    return (la + 0.05) / (lb + 0.05);
  }

  /* ---- чтение пикселей ----
     Снимок рисуется на canvas один раз, и дальше из него берутся
     одиночные пиксели. Раньше здесь считали среднее по полосе под
     подписью, но на этом снимке среднее всегда ноль с копейками,
     и измерение превращалось в константу, которая ничего не
     проверяла. Одиночный пиксель честнее: показывает, что под
     линзой, а не «в среднем под линзой». */
  function prepare() {
    if (measured) {
      return;
    }
    if (!pic.naturalWidth) {
      return;
    }
    try {
      canvas = document.createElement('canvas');
      canvas.width = pic.naturalWidth;
      canvas.height = pic.naturalHeight;
      ctx = canvas.getContext('2d', { willReadFrequently: true });
      if (!ctx) {
        return;
      }
      ctx.drawImage(pic, 0, 0);
      pixels = ctx.getImageData(0, 0, canvas.width, canvas.height).data;
      measured = true;
    } catch (e) {
      /* Пиксели недоступны (например, снимок подан как вставка из
         буфера и canvas оказался «испорченным»). Молча подставить
         придуманное значение нельзя, поэтому лупа продолжает
         работать как лупа, а вывод честно говорит, что замера нет. */
      measured = true;
      pixels = null;
    }
  }

  /* Геометрия линзы. Считается от фактического размера снимка на
     экране, а не от width/494 в атрибутах: атрибуты описывают
     картинку, а не то, во сколько она вписана в колонку, и при
     другой ширине экрана лупа уехала бы мимо. */
  function metrics() {
    var w = pic.clientWidth;
    var h = pic.clientHeight;
    return {
      w: w,
      h: h,
      r: Math.round(Math.min(w * RADIUS_RATIO, h * RADIUS_RATIO, 74))
    };
  }

  /* Постановка линзы. frac — доля высоты снимка от 0 до 1.
     Положение по горизонтали фиксировано: снимок вертикальный и
     вести лупу по высоте естественнее, чем по ширине. */
  function place(frac) {
    var m = metrics();
    if (!m.w || !m.h) {
      return;
    }

    var r = Math.max(12, m.r);
    var cy = frac * m.h;

    /* Край кадра не даёт линзе выехать за снимок. Сдвигаем внутрь
       вместо обрезки круга об overflow:hidden: половина линзы за
       краем снимка читается как ошибка вёрстки, а не как линза,
       лежащая на поверхности. */
    var cx = m.w / 2;
    var cyClamped = Math.min(Math.max(cy, r), m.h - r);

    loupe.style.width = (r * 2) + 'px';
    loupe.style.height = (r * 2) + 'px';
    loupe.style.left = Math.round(cx - r) + 'px';
    loupe.style.top = Math.round(cyClamped - r) + 'px';

    /* Копия снимка внутри линзы должна быть того же размера, что и
       .pic, и сдвинута так, чтобы точка (cx, cyClamped) исходной
       картинки попала в центр видимого круга.

       Порядок прямоугольников важен, и в нём легко ошибиться.
       Вывод формулы — единственное место в файле, где нужна
       осторожность, и записан он так, чтобы его можно было
       проверить пересчётом, а не соображением «так вроде верно»:

         1. лупа стоит на (cx - r, cy - r), а копия снимка внутри
            неё сдвинута на -(cx - r), -(cy - r). Два сдвига
            взаимно уничтожаются: левый верхний угол копии
            совпадает с левым верхним углом кадра. Значит
            координаты точки кадра и координаты той же точки
            внутри копии — одни и те же числа, пересчёта между
            системами координат не требуется вовсе.
         2. transform с transform-origin 0 0 переводит точку
            (x, y) в (tx + x*ZOOM, ty + y*ZOOM).
         3. мы хотим, чтобы точка кадра (cx, cyClamped) — та, что
            под центром лупы — оказалась в центре видимого круга,
            а в координатах лупы это (r, r).
         4. отсюда tx + cx*ZOOM = r, то есть tx = r - cx*ZOOM.

       Ошибка в шаге 1 стоила бы сотни пикселей сдвига: при
       tx = cx - cx*ZOOM получилось бы tx + cx*ZOOM = cx вместо r,
       то есть лупа показывала бы не то место, где стоит, и на
       этой колонке разъехалась бы примерно на сотню пикселей.
       Формула проверяется пересчётом по всей сетке положений
       ползунка, а не на глаз. */
    loupePic.style.width = m.w + 'px';
    loupePic.style.height = m.h + 'px';
    loupePic.style.left = Math.round(-(cx - r)) + 'px';
    loupePic.style.top = Math.round(-(cyClamped - r)) + 'px';
    loupePic.style.transform =
      'translate(' + (r - cx * ZOOM).toFixed(2) + 'px,' +
                    (r - cyClamped * ZOOM).toFixed(2) + 'px) ' +
      'scale(' + ZOOM + ')';

    report(cyClamped / m.h);
  }

  /* Вывод. Тон пикселя — правда из снимка. Контраст подписи на
     этом тоне — проверка читаемости: если он ниже порога,
     значит светлая подпись на таком фоне сама по себе не годится
     и держит её только подложка. Проверить это полезно: при замене
     снимка страница сразу скажет, что подпись на нём не читается.
     Подложка в CSS постоянная, и её хватает по замеру
     (см. шапку style.css), поэтому «ниже порога» здесь означает не
     «текст нечитаем», а «подложка работает вовсю». */
  function report(actualFrac) {
    prepare();

    if (!pixels) {
      out.textContent =
        'тон под линзой: измерить не вышло (пиксели снимка ' +
        'недоступны) · увеличение ×' + ZOOM;
      return;
    }

    /* Пиксель берётся в центре линзы: ровно в той точке, которую
       человек видит увеличенной, то есть ровно там, куда смотрит. */
    var ix = Math.round(canvas.width / 2);
    var iy = Math.min(canvas.height - 1,
                      Math.round(actualFrac * (canvas.height - 1)));
    var o = (iy * canvas.width + ix) * 4;

    var rgb = [
      Math.round(pixels[o]),
      Math.round(pixels[o + 1]),
      Math.round(pixels[o + 2])
    ];

    /* Считаем по BAND_DIM — самому тёмному из цветов подписи: метка
       на тон тусклее основного текста, и если контраст проходит
       для неё, то проходит и для всего остального. */
    var cDim = contrast(rgb, BAND_DIM);

    var text =
      'тон под линзой: rgb(' + rgb[0] + ', ' + rgb[1] + ', ' + rgb[2] + ')' +
      ' · увеличение ×' + ZOOM +
      ' · высота: ' + Math.round(actualFrac * 100) + '%' +
      ' · подпись: ' + cDim.toFixed(2) + ':1';

    if (cDim < MIN_CONTRAST) {
      text += ' — ниже порога ' + MIN_CONTRAST.toFixed(1) + ':1, ' +
              'подложка держит';
    }

    out.textContent = text;
  }

  range.addEventListener('input', function () {
    place(Number(range.value) / 100);
  });

  /* Мышь и палец. Обработчик на кадре, а не на самой картинке:
     кадр включает и лупу, и наведение на неё не должно рвать
     перемещение. Координаты берём относительно .pic, а не кадра:
     кадр и картинка совпадают по высоте, но брать прямоугольник
     кадра — значит положиться на совпадение, которое держится
     только до первой правки отступов. */
  frame.addEventListener('pointermove', function (ev) {
    var box = pic.getBoundingClientRect();
    if (!box.height) {
      return;
    }
    place((ev.clientY - box.top) / box.height);
  });

  /* Перенос на телефоне и поворот экрана меняют размер колонки, а
     вместе с ним и радиус линзы. Без пересчёта она либо разъехалась
     бы с центром, либо осталась бы прежнего размера. */
  var resizeTimer = null;
  window.addEventListener('resize', function () {
    if (resizeTimer) {
      window.clearTimeout(resizeTimer);
    }
    /* С задержкой: во время переноса колонка меняет ширину
       десятки раз, и без задержки лупа мигала бы на каждом шаге. */
    resizeTimer = window.setTimeout(function () {
      place(Number(range.value) / 100);
    }, 90);
  });

  if (pic.complete && pic.naturalWidth) {
    place(Number(range.value) / 100);
  } else {
    pic.addEventListener('load', function () {
      place(Number(range.value) / 100);
    });
  }
}());