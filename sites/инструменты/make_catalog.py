def esc(text: str) -> str:
    return html_mod.escape(text)


def load_shots() -> dict:
    if not SHOTS_JSON.is_file():
        return {}
    try:
        return json.loads(SHOTS_JSON.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def check_targets() -> list[str]:
    """Найти расхождения между списком и тем, что есть на диске.

    Где искать страницу, решает не сам список, а устройство проекта:
    портфолио лежит в `portfolios/` и выкладывается отдельным
    загрузчиком, всё остальное — в `site/`. Раньше проверка искала всё
    в `site/` и ругалась на семь подач, которые на месте и работают.
    """
    problems = []
    portfolios = ROOT / "portfolios"

    # 1. Обещанной страницы нет — карточка врёт.
    for path, name, *_ in SITES:
        if path == "/":
            # Корень сайта. Проверять папку `site/` бессмысленно:
            # каталог увидит каталог и решит, что всё в порядке.
            if not (SITE / "index.html").is_file():
                problems.append("нет site/index.html для карточки «Главная»")
        elif path.endswith(".html"):
            if not (SITE / path.lstrip("/")).is_file():
                problems.append(f"нет файла {path} для карточки «{name}»")
        else:
            folder = path.strip("/")
            here = SITE / folder / "index.html"
            there = portfolios / folder / "index.html"
            if not here.is_file() and not there.is_file():
                problems.append(f"нет папки {path} для карточки «{name}» "
                                f"(ни в site/, ни в portfolios/)")

    # 2. Папка есть, а в списках её нет — молча пропала бы из каталога.
    listed = {p.strip("/") for p, *_ in SITES if p.endswith("/")}
    for item in SITE.iterdir():
        if not item.is_dir():
            continue
        if item.name in ("assets", "guide", "demo", "ruffle", "swf",
                         "abstration"):
            continue
        if item.name not in listed and (item / "index.html").is_file():
            problems.append(f"папка site/{item.name} есть, а в каталоге её "
                            f"нет — она пропала бы из витрины")

    # 3. Повтор адреса.
    seen: set[str] = set()
    for path, name, *_ in SITES:
        if path in seen:
            problems.append(f"адрес {path} повторяется («{name}»)")
        seen.add(path)

    return problems


def card(number: str, path: str, name: str, about: str,
         stripe: str, tags: tuple[str, ...],
         shots: dict) -> str:
    """Одна карточка каталога."""
    shot = shots.get(path)
    if shot and shot.get("file"):
        # Снимок настоящего первого экрана. Ширина и высота в разметке
        # обязательны: без них браузер резервирует пустое место и вся
        # страница дёргается, пока грузятся двадцать картинок.
        preview = (
            f'<img class="shot" src="assets/shots/{esc(shot["file"])}" '
            f'width="{shot.get("w", 1280)}" height="{shot.get("h", 800)}" '
            f'loading="lazy" decoding="async" '
            f'alt="Первый экран страницы {esc(name)}">')
    else:
        # Снимка нет — рисуем полосу из палитры страницы. Честнее
        # пустой рамки: видно, что это витрина, а не кадр.
        preview = '<span class="noshot" aria-hidden="true"></span>'

    tag_html = "".join(f"<span>{esc(t)}</span>" for t in tags)
    return (
        f'        <a class="card {stripe}" href="/{esc(path.lstrip("/"))}">\n'
        f'          <span class="num">{number}</span>\n'
        f'          {preview}\n'
        f'          <div class="body">\n'
        f'            <h3>{esc(name)}</h3>\n'
        f'            <p class="where">/{esc(path.lstrip("/"))}</p>\n'
        f'            <p class="about">{esc(about)}</p>\n'
        f'            <p class="tags">{tag_html}</p>\n'
        f'          </div>\n'
        f'        </a>')


