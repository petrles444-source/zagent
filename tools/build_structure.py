def write(path: Path, text: str, dry: bool) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if dry:
        print(f"  просмотр: {path.relative_to(ROOT)}")
        return
    path.write_text(text, encoding="utf-8")
    print(f"  записан: {path.relative_to(ROOT)}")


def copy_tree(src: Path, dst: Path, skip: tuple[str, ...],
              dry: bool) -> int:
    """Скопировать дерево, пропуская мусор и кэши."""
    if dry:
        count = len([f for f in src.rglob("*")
                     if f.is_file()
                     and not any(s in f.parts for s in skip)])
        print(f"  просмотр: {dst.relative_to(ROOT)} "
              f"({count} файлов из {src.relative_to(ROOT)})")
        return count
    count = 0
    for item in src.rglob("*"):
        if any(part in skip for part in item.parts):
            continue
        rel = item.relative_to(src)
        target = dst / rel
        if item.is_dir():
            target.mkdir(parents=True, exist_ok=True)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item, target)
            count += 1
    print(f"  скопировано: {dst.relative_to(ROOT)} ({count} файлов)")
    return count


